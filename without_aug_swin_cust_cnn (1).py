def inference_on_image(model, image_path,  swin_processor, device, class_names):
    """
    Perform inference on a single image

    Args:
        model: Trained model
        image_path: Path to the image
        vit_processor: ViT image processor
        device: Device to use for inference
        class_names: List of class names

    Returns:
        predicted_class: Predicted class name
        confidence: Confidence score
    """
    # Load and preprocess the image
    image = Image.open(image_path).convert('RGB')

    # Process for ViT
    vit_processed =  swin_processor(images=image, return_tensors="pt")
    vit_pixels = vit_processed.pixel_values.squeeze().to(device)

    # Process for CNN
    cnn_transform = transforms.Compose([
        transforms.Resize(224),
        transforms.CenterCrop(224),
        transforms.ToTensor(),
        transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
    ])
    cnn_pixels = cnn_transform(image).to(device)

    # Add batch dimension
    vit_pixels = vit_pixels.unsqueeze(0)
    cnn_pixels = cnn_pixels.unsqueeze(0)

    # Set model to evaluation mode
    model.eval()

    # Perform inference
    with torch.no_grad():
        outputs = model(vit_pixels, cnn_pixels)
        probs = torch.nn.functional.softmax(outputs, dim=1)
        confidence, predicted = torch.max(probs, 1)

    # Get predicted class name
    predicted_class = class_names[predicted.item()]

    return predicted_class, confidence.item()

def analyze_gradcam(model, image_path, swin_processor, device, class_names, save_dir='./plots'):
    """
    Analyze model predictions using GradCAM

    Args:
        model: Trained model
        image_path: Path to the image
        vit_processor: ViT image processor
        device: Device to use for inference
        class_names: List of class names
        save_dir: Directory to save plots
    """
    os.makedirs(save_dir, exist_ok=True)

    # Load and preprocess the image
    image = Image.open(image_path).convert('RGB')
    image_np = np.array(image)

    # Process for CNN
    cnn_transform = transforms.Compose([
        transforms.Resize(224),
        transforms.CenterCrop(224),
        transforms.ToTensor(),
        transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
    ])
    cnn_pixels = cnn_transform(image).to(device)

    # Process for ViT
    vit_processed =  swin_processor(images=image, return_tensors="pt")
    vit_pixels = vit_processed.pixel_values.squeeze().to(device)

    # Add batch dimension
    vit_pixels = vit_pixels.unsqueeze(0)
    cnn_pixels = cnn_pixels.unsqueeze(0)

    # Register hooks for GradCAM
    gradients = []
    activations = []

    def save_gradient(grad):
        gradients.append(grad.cpu().detach())

    def forward_hook(module, input, output):
        activations.append(output.cpu().detach())

    # Register hook for last convolutional layer in CNN
    target_layer = model.cnn.features[-2]  # Last conv layer before ReLU
    hook_handle = target_layer.register_forward_hook(forward_hook)

    # Set model to evaluation mode
    model.eval()

    # Get prediction
    vit_pixels.requires_grad_()
    cnn_pixels.requires_grad_()

    outputs = model(vit_pixels, cnn_pixels)
    predicted_class = torch.argmax(outputs, dim=1).item()

    # Backward pass for GradCAM
    model.zero_grad()

    # Register hook for gradients
    activations[-1].register_hook(save_gradient)

    # Backward pass for the predicted class
    one_hot = torch.zeros_like(outputs)
    one_hot[0, predicted_class] = 1
    outputs.backward(gradient=one_hot)

    # Generate GradCAM
    gradients = gradients[0]
    activations = activations[0]

    # Remove hooks
    hook_handle.remove()

    # Calculate weights
    weights = torch.mean(gradients, dim=(2, 3))

    # Create weighted activation map
    cam = torch.zeros(activations.shape[2:], dtype=torch.float32)
    for i, w in enumerate(weights[0]):
        cam += w * activations[0, i]

    # Apply ReLU to CAM
    cam = np.maximum(cam.numpy(), 0)

    # Normalize CAM
    cam = (cam - cam.min()) / (cam.max() - cam.min() + 1e-8)

    # Resize CAM to match original image
    cam = cv2.resize(cam, (image_np.shape[1], image_np.shape[0]))

    # Convert CAM to heatmap
    heatmap = cv2.applyColorMap(np.uint8(255 * cam), cv2.COLORMAP_JET)
    heatmap = cv2.cvtColor(heatmap, cv2.COLOR_BGR2RGB)

    # Overlay heatmap on original image
    alpha = 0.4
    overlay = heatmap * alpha + image_np * (1 - alpha)
    overlay = overlay.astype(np.uint8)

    # Plot original image and overlay
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 6))
    ax1.imshow(image_np)
    ax1.set_title(f'Original Image\nPredicted: {class_names[predicted_class]}')
    ax1.axis('off')

    ax2.imshow(overlay)
    ax2.set_title('GradCAM Visualization')
    ax2.axis('off')

    plt.tight_layout()

    # Extract filename from path
    filename = os.path.basename(image_path).split('.')[0]
    plt.savefig(f'{save_dir}/gradcam_{filename}.png')
    plt.close()

    return class_names[predicted_class]

